const fs=require('fs'),vm=require('vm'),assert=require('assert');
const c={window:{}};vm.createContext(c);
for(const f of ['data.js','author-identities.js','author-groups.js','author-identity-resolver.js','author-affiliations.js','paper-author-interest.js'])vm.runInContext(fs.readFileSync('outputs/paper-atlas/'+f,'utf8'),c);
const w=c.window,h=w.createPaperAuthorInterest({resolveAuthors:w.resolveAtlasPaperAuthors,affiliations:w.ATLAS_AUTHOR_AFFILIATIONS});
const lab=w.ATLAS_DATA.nodes.filter(p=>p.lab),interest={other:false};
const excludedId='person-e6da050b2d62',retainedId='person-e2c6956bf522';
assert(lab.every(p=>!h.cared(p,{}).some(a=>a.id===excludedId)),'excluded Monash author stays excluded when all groups are cared');
assert.equal(lab.filter(p=>h.cared(p,{}).some(a=>a.id===retainedId)).length,5,'SEU author retains exactly five papers');
for(const e of h.edges(lab,'author',{}))assert(!e.evidence.person_ids.includes(excludedId),'excluded author contributes no shared-person edge');
assert(lab.every(p=>h.keep(p,{})),'default retains unknown-author papers');
assert(lab.every(p=>!h.keep(p,{other:false,current:false,graduated:false})),'no caring authors means no lab seeds');
assert(w.ATLAS_DATA.nodes.filter(p=>!p.lab).every(p=>h.keep(p,interest)),'external neighborhood bypasses author categories');
const kept=lab.filter(p=>h.keep(p,interest));
assert(kept.every(p=>h.cared(p,interest).every(a=>a.group!=='other')));
for(const e of h.edges(kept,'author',interest)){
 assert(e.evidence.authors.every(name=>w.ATLAS_AUTHOR_GROUPS.assignments[w.ATLAS_AUTHOR_IDENTITIES.people.find(p=>(p.display_name||p.name)===name)?.name]),'edge excludes other authors');
 const a=lab.find(p=>p.id===e.source),b=lab.find(p=>p.id===e.target);
 const common=h.cared(a,interest).filter(pa=>h.cared(b,interest).some(pb=>pb.id===pa.id));
 assert.equal(e.score,common.length,'score counts only caring shared people');
}
const person=(id,group)=>({id,name:id,group});
const P=person('current-A','current'),Q=person('current-B','current'),O=person('other-C','other');
const papers=[{id:'a',lab:true,authors:['current-A','other-C']},{id:'b',lab:true,authors:['current-B','other-C']}];
const resolve=p=>p.authors.map(name=>[P,Q,O].find(a=>a.name===name));
const aff={a:[{name:P.name,institutions:[{id:'I1',name:'I1'}]},{name:O.name,institutions:[{id:'I9',name:'I9'}]}],b:[{name:Q.name,institutions:[{id:'I2',name:'I2'}]},{name:O.name,institutions:[{id:'I9',name:'I9'}]}]};
const unit=w.createPaperAuthorInterest({resolveAuthors:resolve,affiliations:aff});
assert(papers.every(p=>unit.keep(p,interest)),'mixed paper survives via cared author');
assert.equal(unit.edges(papers,'author',{}).length,1);
assert.equal(unit.edges(papers,'author',interest).length,0,'ignored common coauthor supplies no edge');
assert.equal(unit.edges(papers,'institution',{}).length,1);
assert.equal(unit.edges(papers,'institution',interest).length,0,'ignored author institution supplies no edge');
assert.equal(unit.edges(papers,'institution',{current:false}).length,1,'shared cared institution retained');
console.log('PASS: caring author seeds, unknown signatures, retained external neighborhood, filtered shared-person strength and per-author institution contributions.');

const densePapers=Array.from({length:10},(_,i)=>({id:'dense-'+i,lab:true,authors:['Shared']}));
const denseAff=Object.fromEntries(densePapers.map(p=>[p.id,[{name:'Shared',institutions:[{id:'shared-I',name:'Shared Institute'}]}]]));
const dense=w.createPaperAuthorInterest({resolveAuthors:()=>[{id:'shared-person',name:'Shared',group:'current'}],affiliations:denseAff});
for(const kind of ['author','institution'])assert.equal(dense.edges(densePapers,kind,{}).length,45,'all qualifying pairs survive without per-paper cap');
const full=JSON.parse(fs.readFileSync('outputs/paper-atlas/relations-full.json','utf8'));
assert.equal(w.ATLAS_DATA.edges.length,full.length,'all precomputed connections restored');
const storedIDs=new Set(w.ATLAS_DATA.edges.map(e=>e.id));assert(full.every(e=>storedIDs.has(e.id)),'every qualifying relation is present');
console.log('PASS: uncapped dense author/institution graphs and all complete precomputed relations.');
