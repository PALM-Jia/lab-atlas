const assert=require('assert'),fs=require('fs'),vm=require('vm');
const build=require('../outputs/paper-atlas/author-keywords.js');
const paper=id=>({id,lab:true});
const keyword=(id,name=id)=>({id,name,score:.9});
const a={id:'a',name:'A',papers:['p1','p2'],paperWeights:{p1:1,p2:.2}};
const b={id:'b',name:'B',papers:['p3'],paperWeights:{p3:.2}};
const c={id:'c',name:'C',papers:['p4']};
const data={papers:{p1:[keyword('k1'),keyword('k1')],p2:[keyword('k2')],p3:[keyword('k1')],p4:[keyword('k3')]},idf:{k1:1,k2:2,k3:1}};
const edges=build({authors:[a,b,c,{id:'missing',name:'M',papers:['p5']}],papers:['p1','p2','p3','p4','p5'].map(paper),keywordData:data});
assert.equal(edges.length,1);assert.equal(edges.stats.valid_pairs,3);assert.equal(edges.stats.positive_pairs,1);
assert.ok(Math.abs(edges[0].score-.625)<1e-12,'min=5/6; max=1+(1/6)*2; first-author contribution not duplicated');
assert.ok(Math.abs(edges[0].evidence.shared_topics[0].source_weight-5/6)<1e-12);
assert.equal(edges[0].evidence.shared_topics[0].target_weight,1);
assert.equal(edges.profiles.length,4,'profiles retained for isolated authors and missing records');
const profile=edges.profiles.find(p=>p.author_id==='a');
assert.equal(profile.keywords.length,2,'complete profile includes non-shared keywords');
assert.ok(Math.abs(profile.keywords[0].weight-5/6)<1e-12);
assert.equal(edges.profiles.find(p=>p.author_id==='missing').profiled_papers,0);
assert.equal(edges[0].evidence.profiles[0],profile,'edge explanation uses the actual matching profile');
assert.deepEqual(edges[0].evidence.shared_topics[0].source_papers,['p1']);
assert.equal(edges[0].evidence.threshold,null);assert.equal(edges[0].evidence.top_k,5);
assert.equal(build({authors:[a,c],papers:['p1','p2','p4'].map(paper),keywordData:data}).length,0,'disjoint keywords do not connect');
assert.equal(build({authors:[a,b],papers:[paper('p2'),paper('p3')],keywordData:data}).length,0,'filtered-out first-author paper cannot contribute');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync('outputs/paper-atlas/paper-keywords.js','utf8'),ctx);
const actual=ctx.window.ATLAS_PAPER_KEYWORDS;
assert.equal(actual.coverage.with_keywords,Object.keys(actual.papers).length);
assert.equal(actual.coverage.with_keywords+actual.coverage.without_keywords,actual.coverage.total);
console.log('Passed: weighted keyword Jaccard, first-author weighting, deduplication, missing records, filtering, top-five selection, coverage.');
